def winui_value(value: str, theme: str) -> str:
    """A role of the apps' set (light or dark), with an opacity, or a colour as it is."""
    if value.startswith("#"):
        return value
    role, _, alpha = value.partition("/")
    base = APPS[role][theme]
    if not alpha:
        return base
    hexa, opacity, name = resolve(base)
    return f"{name or '#' + hexa}/{float(alpha) * opacity}"


def blend(top: str, under: str, opacity: float) -> str:
    """`top` at `opacity` laid on `under`, as one solid colour (#RRGGBB)."""
    (a, _, _), (b, _, _) = resolve(top), resolve(under)
    mix = [round(int(a[i:i + 2], 16) * opacity + int(b[i:i + 2], 16) * (1 - opacity)) for i in (0, 2, 4)]
    return "#" + "".join(f"{c:02X}" for c in mix)


def winui_brush(value, theme: str) -> str:
    if isinstance(value, tuple):
        top, under, opacity = value
        return xaml_color(blend(APPS[top][theme], APPS[under][theme], opacity))
    return xaml_color(winui_value(value, theme))


def winui_font(family: str, weight: str) -> str:
    """A family's key for a weight: each weight is its own file, WinUI would otherwise draw a false bold."""
    files = TOKENS["families"][family]["files"]
    first = next(iter(files))
    return f"GFont{camel(family)}" + ("" if weight == first else camel(weight))


