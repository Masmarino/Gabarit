#!/usr/bin/env python3
"""Gabarit's tokens, from the one source (tokens/gabarit.json) to every platform.

    python3 tools/tokens.py           write the generated files
    python3 tools/tokens.py --check   fail if a generated file is out of date (CI)

Generated, never to be edited by hand:
- web: projects/gabarit/src/lib/tokens/_palette.scss and _themes.scss (the "web" set of roles);
- Swift: swift/GabaritCommon/GTokens.swift (plain values, every platform) and
  swift/GabaritApple/GTokens+SwiftUI.swift (SwiftUI colours, fonts, animations);
- GTK: swift/GabaritGtk/Resources/gabarit-light.css, gabarit-dark.css (colours) and gabarit.css (text);
- WinUI: swift/GabaritWinUI/Resources/Gabarit.xaml;
- Compose: android/gabarit/src/main/kotlin/com/masmarino/gabarit/GTokens.kt;
- symbols: swift/GabaritCommon/GSymbols.swift, from tokens/symbols.json (SF Symbols' names → Phosphor's).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = json.loads((ROOT / "tokens/gabarit.json").read_text(encoding="utf-8"))
HEADER = "Generated by tools/tokens.py from tokens/gabarit.json: do not edit."

SYMBOLS = json.loads((ROOT / "tokens/symbols.json").read_text(encoding="utf-8"))["symbols"]
# Each Phosphor icon's character in its fonts (WinUI), from tools/phosphor.py.
GLYPHS = json.loads((ROOT / "tokens/phosphor-glyphs.json").read_text(encoding="utf-8"))["glyphs"]
# Where an app puts Gabarit's resources (swift/GabaritWinUI/README.md): its fonts, by WinUI's address.
WINUI_FONTS = "ms-appx:///Gabarit/Fonts"
_unknown = sorted(f"{sf} → {ph}" for sf, ph in SYMBOLS.items() if ph not in GLYPHS)
_bad = sorted(sf for sf in SYMBOLS if not re.fullmatch(r"[a-z0-9]+(\.[a-z0-9]+)*", sf) or "fill" in sf.split("."))
if _unknown or _bad:
    sys.exit(f"tokens/symbols.json: Phosphor names unknown {_unknown}; SF names to write without .fill {_bad}")
PALETTE = {name: hexa for group in TOKENS["palette"] for name, hexa in group["colors"].items()}
APPS = TOKENS["semantic"]["apps"]


def resolve(value: str) -> tuple[str, float, str | None]:
    """« slate900 », « slate900/0.07 » or « #383D43 » → (RRGGBB, opacity, palette name or None)."""
    name, _, alpha = value.partition("/")
    opacity = float(alpha) if alpha else 1.0
    if name.startswith("#"):
        return name[1:].upper(), opacity, None
    return PALETTE[name][1:], opacity, name


def css_name(name: str) -> str:
    """slate900 → slate-900."""
    scale = name.rstrip("0123456789")
    return f"{scale}-{name[len(scale):]}"


def camel(name: str) -> str:
    return name[0].upper() + name[1:]


# MARK: Web

def web_palette() -> str:
    lines = ["// The raw colours of the Ferris family. Components never read these: they go through the semantic",
             "// tokens, which pick a step per theme.",
             f"// {HEADER}",
             ":root {"]
    for index, group in enumerate(TOKENS["palette"]):
        if index:
            lines.append("")
        if "comment" in group:
            lines.append(f"  // {group['comment']}")
        lines += [f"  --{css_name(name)}: {hexa.lower()};" for name, hexa in group["colors"].items()]
    return "\n".join(lines + ["}", ""])


THEMES_HEAD = """// The themes as mixins, with no output of their own: _semantic puts them on :root, and the parts drawn
// on the graphite frame (the shell's rail and bar, the sign-in page) take the frame's.
//
// Every text token reaches 7:1 on the page and on a panel (contrast.spec.ts), which is why a few of
// them sit a shade darker (or lighter, in the dark) than the marks of the same colour. The status
// tints are translucent, so they take the colour of the ground they sit on.
"""

THEMES_TAIL = """
// The graphite frame, the same in both themes: the dark tokens on a ground a little deeper than the
// dark theme's own. The rail's links are a step brighter, since light thin text on graphite reads
// paler than its ratio says.
@mixin frame-tokens {
  @include dark-tokens;
  --bg-panel: var(--graphite-950);
  --text-secondary: var(--graphite-200);
  color-scheme: dark;
  color: var(--text-primary);
}
"""


def web_themes() -> str:
    def block(items: list[dict]) -> list[str]:
        out = []
        for item in items:
            if item.get("blank"):
                out.append("")
            elif "comment" in item:
                out.append(f"  // {item['comment']}")
            else:
                value = item["value"]
                value = f"var(--{css_name(value)})" if value in PALETTE else value
                out.append(f"  --{item['name']}: {value};")
        return out

    web = TOKENS["semantic"]["web"]
    lines = THEMES_HEAD.split("\n")[:-1] + [f"// {HEADER}", "", "@mixin light-tokens {"] + block(web["light"])
    lines += ["}", "", "@mixin dark-tokens {"] + block(web["dark"]) + ["}"]
    return "\n".join(lines) + "\n" + THEMES_TAIL


# MARK: Swift

def swift_rgba(value: str) -> str:
    hexa, opacity, name = resolve(value)
    if name:
        return f"GPaletteValues.{name}" if opacity == 1 else f"GPaletteValues.{name}.opacity({opacity})"
    return f"GRGBA(hex: 0x{hexa})" if opacity == 1 else f"GRGBA(hex: 0x{hexa}, alpha: {opacity})"


