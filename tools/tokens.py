def swift_symbols() -> str:
    entries = "\n".join(f'        "{sf}": "{ph}",' for sf, ph in SYMBOLS.items())
    characters = "\n".join(f'        "{ph}": "\\u{{{GLYPHS[ph]}}}",' for ph in sorted(set(SYMBOLS.values())))
    return f"""// Generated by tools/tokens.py from tokens/symbols.json: do not edit.

import Foundation

/// The apps write SF Symbols' names everywhere; Apple draws them, GTK and WinUI draw Phosphor's icons (MIT), filled when
/// the name has ".fill" (`gabarit-ph-<name>-symbolic`, `gabarit-ph-<name>-fill-symbolic` under GTK; a character of
/// `font` or `fillFont` under WinUI).
public enum GSymbols {{
    /// An SF Symbol's name, without ".fill", → Phosphor's.
    public static let phosphor: [String: String] = [
{entries}
    ]

    /// Phosphor's fonts under WinUI (a FontIcon's FontFamily): the same character for an icon in both.
    public static let font = "{WINUI_FONTS}/Phosphor.ttf#Phosphor"
    public static let fillFont = "{WINUI_FONTS}/Phosphor-Fill.ttf#Phosphor-Fill"

    /// A Phosphor icon's character in its fonts (WinUI).
    public static let character: [String: String] = [
{characters}
    ]

    /// A symbol's character under WinUI (a FontIcon's Glyph) and its font (`fillFont` when filled), or nil.
    public static func glyph(for symbol: String) -> (character: String, font: String)? {{
        guard let icon = phosphor(for: symbol), let character = character[icon.name] else {{ return nil }}
        return (character: character, font: icon.filled ? fillFont : font)
    }}

    /// A symbol's Phosphor icon (its name, filled or not), or nil if Gabarit does not know it.
    public static func phosphor(for symbol: String) -> (name: String, filled: Bool)? {{
        // "fill" as a part of the name ("lock.fill", "person.fill.badge.plus"), not "filled" ("circle.lefthalf.filled").
        let parts = symbol.split(separator: ".")
        let plain = parts.filter {{ $0 != "fill" }}.joined(separator: ".")
        return phosphor[plain].map {{ (name: $0, filled: plain.count < symbol.count) }}
    }}
}}
"""


