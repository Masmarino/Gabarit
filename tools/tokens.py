#!/usr/bin/env python3
"""Gabarit's tokens, from the one source (tokens/gabarit.json) to every platform.

    python3 tools/tokens.py           write the generated files
    python3 tools/tokens.py --check   fail if a generated file is out of date (CI)

Generated, never to be edited by hand:
- web: projects/gabarit/src/lib/tokens/_palette.scss and _themes.scss (the "web" set of roles);
- Swift: swift/GabaritCommon/GTokens.swift (plain values, every platform) and
  swift/GabaritApple/GTokens+SwiftUI.swift (SwiftUI colours, fonts, animations);
- GTK: swift/GabaritGtk/Resources/gabarit-light.css, gabarit-dark.css (colours) and gabarit.css (text);
- WinUI: swift/GabaritWinUI/Resources/Gabarit.xaml;
- Compose: android/gabarit/src/main/kotlin/com/masmarino/gabarit/GTokens.kt.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = json.loads((ROOT / "tokens/gabarit.json").read_text())
HEADER = "Generated by tools/tokens.py from tokens/gabarit.json: do not edit."

PALETTE = {name: hexa for group in TOKENS["palette"] for name, hexa in group["colors"].items()}
APPS = TOKENS["semantic"]["apps"]


def resolve(value: str) -> tuple[str, float, str | None]:
    """« slate900 », « slate900/0.07 » or « #383D43 » → (RRGGBB, opacity, palette name or None)."""
    name, _, alpha = value.partition("/")
    opacity = float(alpha) if alpha else 1.0
    if name.startswith("#"):
        return name[1:].upper(), opacity, None
    return PALETTE[name][1:], opacity, name


def css_name(name: str) -> str:
    """slate900 → slate-900."""
    scale = name.rstrip("0123456789")
    return f"{scale}-{name[len(scale):]}"


def camel(name: str) -> str:
    return name[0].upper() + name[1:]


# MARK: Web

def web_palette() -> str:
    lines = ["// The raw colours of the Ferris family. Components never read these: they go through the semantic",
             "// tokens, which pick a step per theme.",
             f"// {HEADER}",
             ":root {"]
    for index, group in enumerate(TOKENS["palette"]):
        if index:
            lines.append("")
        if "comment" in group:
            lines.append(f"  // {group['comment']}")
        lines += [f"  --{css_name(name)}: {hexa.lower()};" for name, hexa in group["colors"].items()]
    return "\n".join(lines + ["}", ""])


THEMES_HEAD = """// The themes as mixins, with no output of their own: _semantic puts them on :root, and the parts drawn
// on the graphite frame (the shell's rail and bar, the sign-in page) take the frame's.
//
// Every text token reaches 7:1 on the page and on a panel (contrast.spec.ts), which is why a few of
// them sit a shade darker (or lighter, in the dark) than the marks of the same colour. The status
// tints are translucent, so they take the colour of the ground they sit on.
"""

THEMES_TAIL = """
// The graphite frame, the same in both themes: the dark tokens on a ground a little deeper than the
// dark theme's own. The rail's links are a step brighter, since light thin text on graphite reads
// paler than its ratio says.
@mixin frame-tokens {
  @include dark-tokens;
  --bg-panel: var(--graphite-950);
  --text-secondary: var(--graphite-200);
  color-scheme: dark;
  color: var(--text-primary);
}
"""


def web_themes() -> str:
    def block(items: list[dict]) -> list[str]:
        out = []
        for item in items:
            if item.get("blank"):
                out.append("")
            elif "comment" in item:
                out.append(f"  // {item['comment']}")
            else:
                value = item["value"]
                value = f"var(--{css_name(value)})" if value in PALETTE else value
                out.append(f"  --{item['name']}: {value};")
        return out

    web = TOKENS["semantic"]["web"]
    lines = THEMES_HEAD.split("\n")[:-1] + [f"// {HEADER}", "", "@mixin light-tokens {"] + block(web["light"])
    lines += ["}", "", "@mixin dark-tokens {"] + block(web["dark"]) + ["}"]
    return "\n".join(lines) + "\n" + THEMES_TAIL


# MARK: Swift

def swift_rgba(value: str) -> str:
    hexa, opacity, name = resolve(value)
    if name:
        return f"GPaletteValues.{name}" if opacity == 1 else f"GPaletteValues.{name}.opacity({opacity})"
    return f"GRGBA(hex: 0x{hexa})" if opacity == 1 else f"GRGBA(hex: 0x{hexa}, alpha: {opacity})"


def swift_common() -> str:
    lines = [f"// {HEADER}", "",
             "/// A colour as four components from 0 to 1, with no UI framework: each platform turns it into its own.",
             "public struct GRGBA: Sendable, Hashable {",
             "    public let red: Double, green: Double, blue: Double, alpha: Double", "",
             "    public init(hex: UInt32, alpha: Double = 1) {",
             "        red = Double((hex >> 16) & 0xFF) / 255",
             "        green = Double((hex >> 8) & 0xFF) / 255",
             "        blue = Double(hex & 0xFF) / 255",
             "        self.alpha = alpha",
             "    }", "",
             "    public func opacity(_ alpha: Double) -> GRGBA {",
             "        GRGBA(red: red, green: green, blue: blue, alpha: alpha)",
             "    }", "",
             "    init(red: Double, green: Double, blue: Double, alpha: Double) {",
             "        (self.red, self.green, self.blue, self.alpha) = (red, green, blue, alpha)",
             "    }",
             "}", "",
             "/// A colour for the light and the dark appearance.",
             "public struct GColorPair: Sendable, Hashable {",
             "    public let light: GRGBA",
             "    public let dark: GRGBA",
             "}", "",
             "/// The raw palette. Views read the colours by role (`GColorValues`), not these.",
             "public enum GPaletteValues {"]
    lines += [f"    public static let {name} = GRGBA(hex: 0x{hexa[1:]})" for name, hexa in PALETTE.items()]
    lines += ["}", "", "/// The colours by role (the apps' set: SkollN's design).", "public enum GColorValues {"]
    lines += [f"    public static let {name} = GColorPair(light: {swift_rgba(v['light'])}, dark: {swift_rgba(v['dark'])})"
              for name, v in APPS.items()]
    lines += ["}", "", "public enum GRadius {"]
    lines += [f"    public static let {name}: Double = {value}" for name, value in TOKENS["radius"].items()]
    lines += ["}", "", "public enum GSpacing {"]
    lines += [f"    public static let {name}: Double = {value}" for name, value in TOKENS["spacing"].items()]
    lines += ["}", "", "public enum GOpacity {"]
    lines += [f"    public static let {name}: Double = {value}" for name, value in TOKENS["opacity"].items()]
    lines += ["}", "", "public struct GShadowSpec: Sendable, Hashable {",
              "    public let color: GRGBA",
              "    public let radius: Double, x: Double, y: Double",
              "}", "", "public enum GShadowValues {"]
    for name, s in TOKENS["shadows"].items():
        lines.append(f"    public static let {name} = GShadowSpec(color: {swift_rgba(s['color'])}, radius: {s['radius']}, "
                     f"x: {s['x']}, y: {s['y']})")
    lines += ["}", "", "public enum GAnimationCurve: Sendable, Hashable {",
              "    case spring(response: Double, damping: Double)",
              "    case easeInOut(duration: Double)",
              "    case easeOut(duration: Double)",
              "    case linear(duration: Double)",
              "}", "", "public enum GAnimationValues {"]
    for name, a in TOKENS["animations"].items():
        curve = (f".spring(response: {a['response']}, damping: {a['damping']})" if a["curve"] == "spring"
                 else f".{a['curve']}(duration: {a['duration']})")
        lines.append(f"    public static let {name} = GAnimationCurve{curve}")
    lines += ["}", "", "/// The font families, and the files each one ships (in GabaritApple's resources).",
              "public enum GFamily: String, Sendable, CaseIterable {"]
    lines += [f"    case {name} = \"{f['name']}\"" for name, f in TOKENS["families"].items()]
    files = [file for f in TOKENS["families"].values() for file in f["files"].values()]
    lines += ["", "    public static let files = [" + ", ".join(f'"{f}"' for f in files) + "]", "}", "",
              "public enum GWeight: String, Sendable { case regular, medium, semibold }", "",
              "/// A text style: its family and weight, its size on a phone and on a computer, and the system style it",
              "/// scales with (Dynamic Type).",
              "public struct GTextStyle: Sendable, Hashable {",
              "    public let family: GFamily",
              "    public let weight: GWeight",
              "    public let phone: Double",
              "    public let desktop: Double",
              "    public let system: String",
              "}", "", "public enum GTextStyles {"]
    for name, t in TOKENS["text"].items():
        lines.append(f"    public static let {name} = GTextStyle(family: .{t['family']}, weight: .{t['weight']}, "
                     f"phone: {t['phone']}, desktop: {t['desktop']}, system: \"{t['system']}\")")
    lines += ["}", ""]
    return "\n".join(lines)


def swift_apple() -> str:
    lines = [f"// {HEADER}", "#if canImport(SwiftUI)", "import SwiftUI", "",
             "/// The raw palette, as SwiftUI colours.", "public enum GPalette {"]
    lines += [f"    public static let {name} = Color(GPaletteValues.{name})" for name in PALETTE]
    themable = TOKENS["semantic"]["themable"]
    lines += ["}", "", "/// The colours by role, light and dark. The grounds an application may replace (`GTheme`) are read at",
              "/// each use: a view redraws when they change.", "public enum GColor {"]
    for name in APPS:
        if name in themable:
            lines.append(f"    public static var {name}: Color {{ GTheme.current.{name} ?? GColorDefault.{name} }}")
        else:
            lines.append(f"    public static let {name} = Color(GColorValues.{name})")
    lines += ["}", "", "/// The grounds as Gabarit draws them, with no theme.", "public enum GColorDefault {"]
    lines += [f"    public static let {name} = Color(GColorValues.{name})" for name in themable]
    lines += ["}", "", "/// The grounds an application replaces for its colour themes (nil: Gabarit's own). Observed.",
              "@Observable", "public final class GTheme: @unchecked Sendable {",
              "    public static let current = GTheme()", ""]
    lines += [f"    public var {name}: Color?" for name in themable]
    lines += ["", "    public init() {}", "}", "", "/// The text styles: the computer's sizes on a Mac, the phone's elsewhere; they follow Dynamic Type.",
              "public enum GFont {"]
    for platform, key in (("#if os(macOS)", "desktop"), ("#else", "phone")):
        lines.append(f"    {platform}")
        for name in TOKENS["text"]:
            lines.append(f"    public static var {name}: Font {{ Font(GTextStyles.{name}, size: GTextStyles.{name}.{key}) }}")
    lines += ["    #endif", "}", "", "public enum GAnimation {"]
    lines += [f"    public static let {name} = Animation(GAnimationValues.{name})" for name in TOKENS["animations"]]
    lines += ["}", "#endif", ""]
    return "\n".join(lines)


# MARK: GTK

def gtk_color(value: str) -> str:
    hexa, opacity, _ = resolve(value)
    return f"#{hexa}" if opacity == 1 else f"alpha(#{hexa}, {opacity})"


def gtk_colors(key: str) -> str:
    lines = [f"/* {HEADER} */", f"/* The colours by role, {key} appearance: load this file or the other one, then gabarit.css. */"]
    lines += [f"@define-color g_{n} {gtk_color(PALETTE[n])};" for n in PALETTE]
    lines += [f"@define-color g_{name} {gtk_color(v[key])};" for name, v in APPS.items()]
    return "\n".join(lines) + "\n"


WEIGHTS = {"regular": (400, "Normal"), "medium": (500, "Medium"), "semibold": (600, "SemiBold")}


def gtk_text() -> str:
    lines = [f"/* {HEADER} */", "/* The text styles, at the computer's sizes. */"]
    for name, t in TOKENS["text"].items():
        family = TOKENS["families"][t["family"]]["name"]
        lines.append(f".g-{name} {{ font-family: \"{family}\"; font-size: {t['desktop']}px; "
                     f"font-weight: {WEIGHTS[t['weight']][0]}; }}")
    return "\n".join(lines) + "\n"


# MARK: WinUI

def xaml_color(value: str) -> str:
    hexa, opacity, _ = resolve(value)
    return f"#{round(opacity * 255):02X}{hexa}"


def winui() -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->",
             '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
             '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
             "    <ResourceDictionary.ThemeDictionaries>"]
    for theme, key in (("Light", "light"), ("Dark", "dark")):
        lines.append(f'        <ResourceDictionary x:Key="{theme}">')
        for name, v in APPS.items():
            lines.append(f'            <Color x:Key="G{camel(name)}Color">{xaml_color(v[key])}</Color>')
            lines.append(f'            <SolidColorBrush x:Key="G{camel(name)}Brush" Color="{xaml_color(v[key])}"/>')
        lines.append("        </ResourceDictionary>")
    lines.append("    </ResourceDictionary.ThemeDictionaries>")
    lines += [f'    <Color x:Key="GPalette{camel(name)}">{xaml_color(name)}</Color>' for name in PALETTE]
    for name, value in TOKENS["radius"].items():
        lines.append(f'    <x:Double x:Key="GRadius{camel(name)}">{value}</x:Double>')
        lines.append(f'    <CornerRadius x:Key="GCornerRadius{camel(name)}">{value}</CornerRadius>')
    lines += [f'    <x:Double x:Key="GSpacing{camel(name)}">{value}</x:Double>' for name, value in TOKENS["spacing"].items()]
    lines += [f'    <x:Double x:Key="GOpacity{camel(name)}">{value}</x:Double>' for name, value in TOKENS["opacity"].items()]
    for name, f in TOKENS["families"].items():
        first = next(iter(f["files"].values()))
        lines.append(f'    <FontFamily x:Key="GFont{camel(name)}">/Fonts/{first}#{f["name"]}</FontFamily>')
    for name, t in TOKENS["text"].items():
        lines += [f'    <Style x:Key="GText{camel(name)}" TargetType="TextBlock">',
                  f'        <Setter Property="FontFamily" Value="{{StaticResource GFont{camel(t["family"])}}}"/>',
                  f'        <Setter Property="FontSize" Value="{t["desktop"]}"/>',
                  f'        <Setter Property="FontWeight" Value="{WEIGHTS[t["weight"]][1]}"/>',
                  "    </Style>"]
    lines.append("</ResourceDictionary>")
    return "\n".join(lines) + "\n"


# MARK: Compose

def kotlin_color(value: str) -> str:
    hexa, opacity, name = resolve(value)
    base = f"GPalette.{name}" if name else f"Color(0xFF{hexa})"
    return base if opacity == 1 else f"{base}.copy(alpha = {opacity}f)"


def kotlin() -> str:
    lines = [f"// {HEADER}", "package com.masmarino.gabarit", "",
             "import androidx.compose.runtime.Immutable",
             "import androidx.compose.ui.graphics.Color",
             "import androidx.compose.ui.unit.dp", "",
             "/** The raw palette. */", "object GPalette {"]
    lines += [f"    val {name} = Color(0xFF{hexa[1:]})" for name, hexa in PALETTE.items()]
    lines += ["}", "", "/** The colours by role, for the light or the dark appearance. */", "@Immutable", "data class GColors("]
    lines += [f"    val {name}: Color," for name in APPS]
    lines += [")", ""]
    for theme, key in (("Light", "light"), ("Dark", "dark")):
        lines.append(f"val G{theme}Colors = GColors(")
        lines += [f"    {name} = {kotlin_color(v[key])}," for name, v in APPS.items()]
        lines += [")", ""]
    for kind, key in (("GRadius", "radius"), ("GSpacing", "spacing")):
        lines += [f"object {kind} {{"] + [f"    val {n} = {v}.dp" for n, v in TOKENS[key].items()] + ["}", ""]
    lines += ["object GOpacity {"] + [f"    const val {n} = {v}f" for n, v in TOKENS["opacity"].items()] + ["}", ""]
    return "\n".join(lines)


# MARK: Writing

OUTPUTS = {
    "projects/gabarit/src/lib/tokens/_palette.scss": web_palette,
    "projects/gabarit/src/lib/tokens/_themes.scss": web_themes,
    "swift/GabaritCommon/GTokens.swift": swift_common,
    "swift/GabaritApple/GTokens+SwiftUI.swift": swift_apple,
    "swift/GabaritGtk/Resources/gabarit-light.css": lambda: gtk_colors("light"),
    "swift/GabaritGtk/Resources/gabarit-dark.css": lambda: gtk_colors("dark"),
    "swift/GabaritGtk/Resources/gabarit.css": gtk_text,
    "swift/GabaritWinUI/Resources/Gabarit.xaml": winui,
    "android/gabarit/src/main/kotlin/com/masmarino/gabarit/GTokens.kt": kotlin,
}


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, produce in OUTPUTS.items():
        file = ROOT / path
        content = produce()
        if check:
            if not file.exists() or file.read_text() != content:
                stale.append(path)
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content)
    if stale:
        print("Out of date, run python3 tools/tokens.py:\n  " + "\n  ".join(stale))
        return 1
    print("Tokens: " + ("up to date" if check else f"{len(OUTPUTS)} files written"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
