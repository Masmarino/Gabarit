def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, produce in OUTPUTS.items():
        file = ROOT / path
        content = produce()
        if check:
            if not file.exists() or file.read_text(encoding="utf-8") != content:
                stale.append(path)
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Out of date, run python3 tools/tokens.py:\n  " + "\n  ".join(stale))
        return 1
    print("Tokens: " + ("up to date" if check else f"{len(OUTPUTS)} files written"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
